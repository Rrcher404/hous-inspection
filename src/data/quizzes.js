// Each entry is written as q(id, course, components, difficulty, stem, right, [3 wrong], explain).
// The helper places the correct answer at a rotating index (0,1,2,3,0,...) so the answer
// spread stays even no matter how questions are added. Output shape is exactly §9:
// { id, course, components, difficulty, q, choices, answer, explain }.
//
// Difficulty: 1 = a prerequisite or a key number; 2 = application in the field;
// 3 = NHIE-style scenario that needs two ideas at once.
// Sources for every figure are listed in docs/reports/lindqvist-quizzes.md.

let slot = 0;
function q(id, course, components, difficulty, stem, right, wrong, explain) {
  if (wrong.length !== 3) throw new Error(`quiz ${id}: needs exactly 3 distractors`);
  const answer = slot++ % 4;
  const choices = [...wrong];
  choices.splice(answer, 0, right);
  return { id, course, components, difficulty, q: stem, choices, answer, explain };
}

